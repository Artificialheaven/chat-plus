type Request = { history: Message[]; question: UserMessage; prefix?: AssistantMessage }

/**
 * 执行一次压缩：调用模型生成摘要，成功后写入会话记录。
 * 手动压缩失败时保留错误供界面重试；自动压缩的失败交给回复气泡展示。
 */
const runCompaction = async ({
  sessionId,
  plan,
  history,
  previousSummary,
  previousUpToId,
  beforeTokens,
  keepRounds,
  controller,
  automatic,
}: {
  sessionId: string
  plan: CompactPlan
  history: Message[]
  previousSummary?: string
  previousUpToId?: string
  beforeTokens: number
  keepRounds: number
  controller: AbortController
  automatic: boolean
}): Promise<CompactionResult> => {
  set((state) => ({
    compacting: {
      ...state.compacting,
      [sessionId]: { controller, upToId: plan.upToId, rounds: plan.rounds },
    },
    compactErrors: omitKey(state.compactErrors, sessionId),
  }))
  try {
    const settings = useSettings.getState()
    const summary = await requestCompaction({
      apiKey: settings.apiKey ?? '',
      model: MODEL,
      // 与正式请求一致的 system、消息与工具声明，命中 provider 的前缀缓存。
      system: buildSystemPrompt(previousSummary),
      messages: buildCompactionMessages(history, { upToId: plan.upToId, previousUpToId }),
      tools: serverTools(plan.summarizable.at(-1)?.[1].search ?? false),
      safetyCheck: settings.safetyCheck,
      signal: controller.signal,
    })
    if (controller.signal.aborted) {
      return { status: 'aborted' }
    }
    const afterTokens = estimateSummaryUsage(summary, plan.kept)
    // 摘要没有让上下文变小就没有意义，按压缩失败处理，避免越压越大。
    if (afterTokens >= beforeTokens) {
      throw new ApiError('protocol', { key: 'compactNotSmaller' })
    }
    updateSession(sessionId, (session) => ({
      ...session,
      compaction: {
        summary,
        createdAt: Date.now(),
        upToId: plan.upToId,
        keepRounds,
        rounds: plan.rounds,
        beforeTokens,
        afterTokens,
      },
      updatedAt: Date.now(),
    }))
    persist(sessionId)
    return { status: 'done', summary, afterTokens }
  } catch (error) {
    if (controller.signal.aborted) {
      return { status: 'aborted' }
    }
    if (!automatic) {
      const message = error instanceof Error ? error.message : String(error)
      const localMessage: TranslationMessage = message
        ? { key: 'compactFailedWithReason', params: { message } }
        : { key: 'compactFailed' }
      set((state) => ({
        compactErrors: {
          ...state.compactErrors,
          [sessionId]: {
            message,
            localMessage,
            retryable: isRetryableApiError(error),
            upToId: plan.upToId,
            rounds: plan.rounds,
          },
        },
      }))
    }
    return { status: 'error', error }
  } finally {
    set((state) => ({ compacting: omitKey(state.compacting, sessionId) }))
  }
}

/** 发送前检查阈值；达到阈值且还有可压缩轮次时先压缩，再继续原请求。 */
const autoCompactIfNeeded = async (
  sessionId: string,
  request: Request,
  controller: AbortController
): Promise<CompactionResult | null> => {
  const settings = useSettings.getState()
  if (!settings.autoCompact) {
    return null
  }
  const active = getActiveCompaction(getSession(sessionId)?.compaction, request.history)
  const usage = estimateContextUsage(
    request.history,
    request.question,
    active,
    request.prefix
  )
  if (usage.tokens < settings.compactThreshold) {
    return null
  }
  const plan = planCompaction(
    getContextRounds(request.history),
    settings.compactKeepRounds,
    active?.upToId
  )
  if (!plan) {
    return null
  }
  const before = estimateContextUsage(request.history, undefined, active, request.prefix)
  return runCompaction({
    sessionId,
    plan,
    history: request.history,
    // 只有旧摘要的边界仍落在本次压缩范围内时才合并，避免把要原样保留的轮次重复写进摘要。
    previousSummary:
      active && plan.summarizable.some(([, reply]) => reply.id === active.upToId)
        ? active.summary
        : undefined,
    previousUpToId: active?.upToId,
    beforeTokens: before.tokens,
    keepRounds: settings.compactKeepRounds,
    controller,
    automatic: true,
  })
}

/**
 * 服务端确认上下文超限后的兜底：绕过阈值与保留轮数，压缩尽可能多的轮次。
 * 成功后由调用方重发原请求；失败则保留原报错，不做静默截断。
 */
const compactAfterOverflow = async (
  sessionId: string,
  controller: AbortController
): Promise<boolean> => {
  const session = getSession(sessionId)
  if (!session || get().importingHistory || !useSettings.getState().apiKey) {
    return false
  }
  const path = getVisibleMessages(session)
  const active = getActiveCompaction(session.compaction, path)
  const plan = planCompaction(getContextRounds(path), 0, active?.upToId)
  if (!plan) {
    return false
  }
  const before = estimateContextUsage(path, undefined, active)
  const result = await runCompaction({
    sessionId,
    plan,
    history: path,
    previousSummary:
      active && plan.summarizable.some(([, reply]) => reply.id === active.upToId)
        ? active.summary
        : undefined,
    previousUpToId: active?.upToId,
    beforeTokens: before.tokens,
    keepRounds: 0,
    controller,
    automatic: true,
  })
  return result.status === 'done'
}

export type CompactSessionResult = 'started' | 'empty' | 'busy' | 'unavailable'

/** /compact：手动压缩当前分支；不追加消息，也不触发回复。 */
export const compactSession = (sessionId: string): CompactSessionResult => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return 'unavailable'
  }
  const session = getSession(sessionId)
  if (!session || !useSettings.getState().apiKey) {
    return 'unavailable'
  }
  if (isSessionBusy(sessionId)) {
    return 'busy'
  }
  const settings = useSettings.getState()
  const path = getVisibleMessages(session)
  const active = getActiveCompaction(session.compaction, path)
  const plan = planCompaction(
    getContextRounds(path),
    settings.compactKeepRounds,
    active?.upToId
  )
  if (!plan) {
    return 'empty'
  }
  const before = estimateContextUsage(path, undefined, active)
  void runCompaction({
    sessionId,
    plan,
    history: path,
    previousSummary:
      active && plan.summarizable.some(([, reply]) => reply.id === active.upToId)
        ? active.summary
        : undefined,
    previousUpToId: active?.upToId,
    beforeTokens: before.tokens,
    keepRounds: settings.compactKeepRounds,
    controller: new AbortController(),
    automatic: false,
  })
  return 'started'
}

/**
 * 将 serverId 写回所有引用同一附件的消息。传入 null 会清除超限旧图的 ID，触发补传。
 * 尺寸标记随有效 ID 保存，因为本地保留的是原图，刷新后可以直接复用已检查的上传副本。
 */
const saveServerIds = (sessionId: string, serverIds: ReadonlyMap<string, string | null>) => {
  if (serverIds.size === 0) {
    return
  }
  updateSession(sessionId, (session) => ({
    ...session,
    messages: session.messages.map((message) =>
      message.role === 'user' && message.files.some((file) => serverIds.has(file.id))
        ? {
            ...message,
            files: message.files.map((file) => {
              const serverId = serverIds.get(file.id)
              return serverId === undefined
                ? file
                : { ...file, serverId, imageSizeChecked: file.isImage && serverId !== null }
            }),
          }
        : message
    ),
  }))
  persist(sessionId)
}

/**
 * 附件的服务端 id：已有直接用；正在上传的等待同一任务；否则读取本地原件补传。
 * 本地也没有原件（导入的文档附件只有元数据）时返回 null，该附件只展示、不进入请求。
 */
const ensureServerId = async (apiKey: string, file: FileAttachment): Promise<string | null> => {
  if (file.serverId) {
    return file.serverId
  }
  const task = useUploads.getState().tasks[file.id]
  if (task?.status === 'done') {
    return task.serverId
  }
  const blob = await db.loadFile(file.id)
  if (!blob) {
    return null
  }
  return uploadAttachment(apiKey, file.id, blob, file.name, file.isImage)
}

/** 用会话里的最新消息替换请求快照：重传前会重置附件的 serverId，快照必须跟着更新 */
const refreshRequest = (sessionId: string, request: Request): Request => {
  const session = getSession(sessionId)
  if (!session) {
    return request
  }
  const byId = new Map(session.messages.map((message) => [message.id, message]))
  const pick = <T extends Message>(message: T): T =>
    (byId.get(message.id) as T | undefined) ?? message
  return {
    history: request.history.map(pick),
    question: pick(request.question),
    prefix: request.prefix,
  }
}

/**
 * 发送前补齐附件的 serverId。
 * - 本轮提问的附件并行补齐，任一失败则整体失败，已成功的照常写回，重试时复用成功结果；
 * - 历史轮次（仅进入上下文的）中没有 serverId 的附件，多为导入的图片：从最新的消息往前逐张补传，
 *   失败静默跳过，该附件不进入本次请求，下次发送时再试。
 */
const prepareFiles = async (
  sessionId: string,
  request: Request,
  signal: AbortSignal,
  /** 压缩边界：只在它之后的历史轮次需要补传附件。 */
  skipThroughId?: string
) => {
  const epoch = historyEpoch
  // 服务端判定 file_id 失效时会清掉会话里的 serverId，先用最新消息替换请求快照，
  // 否则快照里仍是旧 id，补传会直接复用它。
  request = refreshRequest(sessionId, request)
  const apiKey = useSettings.getState().apiKey ?? ''
  const serverIds = new Map<string, string>()
  // 停止生成立即生效；上传本身不取消（输入框与其他消息可能共用同一任务），完成后照常写回 serverId
  const aborted = new Promise<never>((_, reject) => {
    signal.addEventListener('abort', () => reject(getAbortReason(signal)), { once: true })
  })
  /** 摘要覆盖的轮次不会进入请求，对应附件也不需要补传。 */
  const contextHistory = () => {
    const boundary = skipThroughId
      ? request.history.findIndex((message) => message.id === skipThroughId)
      : -1
    return boundary >= 0 ? request.history.slice(boundary + 1) : request.history
  }
  // 旧图片超限时先清除 ID，交给下方已有的附件补传流程。
  const files = [
    ...request.question.files,
    ...getContextRounds(contextHistory()).flatMap(([user]) => user.files),
  ]
  const checked = await Promise.race([checkImageFileIds(files, signal), aborted])
  if (checked.size > 0) {
    saveServerIds(sessionId, checked)
    request = refreshRequest(sessionId, request)
  }
  const uploads = Promise.allSettled(
    request.question.files.map(async (file) => {
      const serverId = await ensureServerId(apiKey, file)
      if (serverId && serverId !== file.serverId) {
        serverIds.set(file.id, serverId)
      }
    })
  )
  void uploads.then(() => {
    if (epoch === historyEpoch) {
      saveServerIds(sessionId, serverIds)
    }
  })
  const results = await Promise.race([uploads, aborted])
  const failed = results.find((result) => result.status === 'rejected')
  if (failed) {
    throw failed.reason
  }

  const pending = new Map<string, FileAttachment>()
  for (const [user] of getContextRounds(contextHistory()).reverse()) {
    for (const file of user.files) {
      if (!file.serverId && !serverIds.has(file.id) && !pending.has(file.id)) {
        pending.set(file.id, file)
      }
    }
  }
  for (const file of pending.values()) {
    throwIfAborted(signal)
    try {
      const serverId = await Promise.race([ensureServerId(apiKey, file), aborted])
      if (serverId) {
        serverIds.set(file.id, serverId)
        saveServerIds(sessionId, new Map([[file.id, serverId]]))
      }
    } catch {
      throwIfAborted(signal)
    }
  }

  // 用补齐后的会话重新取历史与提问，保证请求里都是 serverId
  const session = getSession(sessionId)
  const resolve = <T extends Message>(message: T): T =>
    (session?.messages.find((m) => m.id === message.id) as T | undefined) ?? message
  return {
    history: request.history.map(resolve),
    question: resolve(request.question),
    prefix: request.prefix,
  }
}

/** 本次请求实际会用到的服务端 file_id */
const collectServerFileIds = (request: Request): Set<string> => {
  const ids = new Set<string>()
  const add = (files: FileAttachment[]) => {
    for (const file of files) {
      if (file.serverId) {
        ids.add(file.serverId)
      }
    }
  }
  add(request.question.files)
  for (const [user] of getContextRounds(request.history)) {
    add(user.files)
  }
  return ids
}

/**
 * 服务端判定 file_id 失效时，清掉对应附件的 serverId 并丢弃旧的上传任务，
 * 下一次补齐会重新读取本地原件上传。报错里点名了 file_id 就只重置这些，
 * 没点名（如 invalid file_id）则重置本次请求用到的全部附件。
 */
const reuploadInvalidatedFiles = (sessionId: string, request: Request, error: unknown): boolean => {
  if (!(error instanceof ApiError) || !getFileErrorCode(error)) {
    return false
  }
  const mentioned = extractFileIds(error.message)
  // 重试时原始快照里还是上一轮已被清掉的 serverId，先换成会话里的最新消息
  const targets =
    mentioned.length > 0
      ? new Set(mentioned)
      : collectServerFileIds(refreshRequest(sessionId, request))
  const session = getSession(sessionId)
  if (targets.size === 0 || !session) {
    return false
  }
  const localIds: string[] = []
  const messages = session.messages.map((message) => {
    if (message.role !== 'user') {
      return message
    }
    let changed = false
    const files = message.files.map((file) => {
      if (!file.serverId || !targets.has(file.serverId)) {
        return file
      }
      localIds.push(file.id)
      changed = true
      return { ...file, serverId: null }
    })
    return changed ? { ...message, files } : message
  })
  if (localIds.length === 0) {
    return false
  }
  updateSession(sessionId, (current) => ({ ...current, messages }))
  // 上传任务里可能还留着同一个失效的 serverId，清掉后 ensureServerId 才会重新上传
  localIds.forEach(cancelUpload)
  persist(sessionId)
  return true
}

/** 重传前的退避等待；停止生成时立即返回，由调用方按已停止收尾 */
const waitForRetry = (attempt: number, signal: AbortSignal) =>
  new Promise<void>((resolve) => {
    function onAbort() {
      clearTimeout(timer)
      resolve()
    }
    const timer = setTimeout(
      () => {
        signal.removeEventListener('abort', onAbort)
        resolve()
      },
      FILE_RETRY_BASE_DELAY * 2 ** attempt
    )
    signal.addEventListener('abort', onAbort, { once: true })
  })

/**
 * 请求并消费流：先补齐附件的 serverId，再发请求；流式增量按动画帧刷新内存，完成、失败或停止后落盘。
 * 补传失败时回复记为 upload 错误，可重试。
 * 服务端判定 file_id 失效时重新补传后重发，退避重试且次数有上限，超过则按原始报错收尾。
 */
const streamReply = async (sessionId: string, initial: AssistantMessage, request: Request) => {
  const controller = new AbortController()
  if (!getSession(sessionId)?.title) {
    titleRequests.add(controller)
  }
  set((state) => ({ streaming: { ...state.streaming, [sessionId]: controller } }))
  let reply = initial
  let overflowAttempted = false
  let frame = 0
  const flush = () => {
    cancelAnimationFrame(frame)
    frame = 0
    updateReply(sessionId, reply)
  }
  streamFlushes.set(sessionId, flush)

  try {
    // 发送前钩子：达到阈值时先压缩较早的轮次，再发正式请求。
    const auto = await autoCompactIfNeeded(sessionId, request, controller)
    if (auto?.status === 'aborted') {
      reply = settleReply(reply, 'stopped', Date.now())
      return
    }
    if (auto?.status === 'error') {
      const message = auto.error instanceof Error ? auto.error.message : String(auto.error)
      reply = settleReply(reply, 'error', Date.now(), {
        kind: 'compact',
        message,
        status: auto.error instanceof ApiError ? auto.error.status : undefined,
        localMessage: message
          ? { key: 'compactFailedWithReason', params: { message } }
          : { key: 'compactFailed' },
        retryable: isRetryableApiError(auto.error),
      })
      return
    }
    for (let attempt = 0; ; attempt += 1) {
      /** 附件补齐前出错属于上传失败，请求还没有发出 */
      let preparing = true
      let receivedContent = false
      try {
        const compactionForFiles = getActiveCompaction(
          getSession(sessionId)?.compaction,
          request.history
        )
        const prepared = await prepareFiles(
          sessionId,
          request,
          controller.signal,
          compactionForFiles?.upToId
        )
        preparing = false
        // 附件就绪后获取本轮信息；续写沿用原回答快照，重新生成的快照独立保存。
        const latestReminder = prepared.prefix
          ? prepared.prefix.latestReminder
          : createLatestReminder(useSettings.getState())
        reply = { ...reply, latestReminder }
        updateReply(sessionId, reply)
        persist(sessionId)
        // 摘要覆盖的轮次不再回传；摘要本身拼进 system，消息角色保持不变。
        const compaction = getActiveCompaction(
          getSession(sessionId)?.compaction,
          prepared.history
        )
        const boundary = compaction
          ? prepared.history.findIndex((message) => message.id === compaction.upToId)
          : -1
        const messages = toRequestMessages(
          boundary >= 0 ? prepared.history.slice(boundary + 1) : prepared.history,
          prepared.question,
          prepared.prefix,
          initial.thinking ?? false,
          latestReminder
        )
        const settings = useSettings.getState()
        const events = streamMessage(
          settings.apiKey ?? '',
          {
            model: initial.model ?? MODEL,
            system: buildSystemPrompt(compaction?.summary),
            messages,
            thinking: { type: initial.thinking ? 'enabled' : 'disabled' },
            ...(settings.safetyCheck ? { safety_check: SAFETY_CHECK } : {}),
            tools: serverTools(initial.search ?? false),
            ...(titleRequests.has(controller) ? { title: { enabled: true } } : {}),
          },
          controller.signal
        )
        const blockIndexes = new Map<number, number>()
        for await (const event of events) {
          receivedContent ||= event.type === 'content_block_start'
          if (
            event.type === 'message_delta' &&
            (event.delta.stop_reason === 'end_turn' || event.delta.stop_reason === 'max_tokens') &&
            event.delta.title?.trim() &&
            titleRequests.has(controller) &&
            !controller.signal.aborted &&
            !get().importingHistory
          ) {
            const title = event.delta.title.trim()
            updateSession(sessionId, (session) => (session.title ? session : { ...session, title }))
            titleRequests.delete(controller)
          }
          reply = applyEvent(reply, event, Date.now(), blockIndexes)
          if (document.visibilityState === 'hidden') {
            flush()
          } else {
            frame ||= requestAnimationFrame(flush)
          }
        }
        reply = settleReply(reply, 'done', Date.now())
        break
      } catch (error) {
        if (controller.signal.aborted) {
          reply = settleReply(reply, 'stopped', Date.now())
          break
        }
        // 上下文超限：不静默截断历史，做一次最大限度的压缩后重发一次。
        if (
          !overflowAttempted &&
          !receivedContent &&
          isContextOverflowError(error) &&
          (await compactAfterOverflow(sessionId, controller))
        ) {
          overflowAttempted = true
          if (!controller.signal.aborted) {
            continue
          }
        }
        if (preparing) {
          reply = settleReply(reply, 'error', Date.now(), {
            kind: 'upload',
            message: '',
            localMessage: describeUploadError(error),
            retryable: isRetryableApiError(error),
          })
          break
        }
        // 附件失效：重新补传后重发。收到过内容块（含丢弃的客户端工具）后不自动重发。
        if (
          attempt < FILE_RETRY_LIMIT &&
          !receivedContent &&
          reuploadInvalidatedFiles(sessionId, request, error)
        ) {
          await waitForRetry(attempt, controller.signal)
          if (controller.signal.aborted) {
            reply = settleReply(reply, 'stopped', Date.now())
            break
          }
          continue
        }
        if (error instanceof ApiError && error.kind === 'interrupted' && reply.stopReason) {
          // 已收到 message_delta 的结束原因，只是缺了结尾的 message_stop
          reply = settleReply(reply, 'done', Date.now())
        } else if (error instanceof ApiError) {
          reply = settleReply(reply, 'error', Date.now(), {
            kind: error.kind,
            message: error.message,
            status: error.status,
            localMessage: error.localMessage,
          })
        } else {
          reply = settleReply(reply, 'error', Date.now(), {
            kind: 'protocol',
            message: error instanceof Error ? error.message : String(error),
          })
        }
        break
      }
    }
  } finally {
    titleRequests.delete(controller)
    streamFlushes.delete(sessionId)
    cancelAnimationFrame(frame)
    updateReply(sessionId, reply)
    set((state) => ({
      streaming: Object.fromEntries(
        Object.entries(state.streaming).filter(([id]) => id !== sessionId)
      ),
      compacting: omitKey(state.compacting, sessionId),
    }))
    persist(sessionId)
  }
}
